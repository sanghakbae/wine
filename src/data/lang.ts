/** "카베르네 소비뇽·메를로" → "Cabernet Sauvignon · Merlot" */
export function grapeLabel(ko: string): string {
  return ko
    .split(/[·,]/)
    .map((g) => g.trim().replace(/\s*(블렌드|등.*)$/, ""))
    .map((g) => GRAPE_EN[g] ?? "")
    .filter(Boolean)
    .join(" · ");
}

export function regionLabel(area: string, sub?: string): string {
  if (sub && REGION_EN[sub]) return REGION_EN[sub];
  return REGION_EN[area] ?? "";
}
