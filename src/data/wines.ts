const NV = new Set(["moet", "veuve", "freixenet", "armand", "ruinart", "tiopepe", "mateus"]);
const SINCE: Record<string, number> = { almaviva: 1996, whisperingangel: 2006, yellowtail: 2001 };
for (const w of BASE) {
  w.quiz ??= BASE_QUIZ[w.id];
  if (NV.has(w.id)) w.nv = true;
  if (SINCE[w.id]) w.since = SINCE[w.id];
}

/** 기본 52종 + 지역별 추가 목록. id 가 겹치면 먼저 나온 것을 쓴다. */
export const WINES: Wine[] = (() => {
  const seen = new Set<string>();
  const out: Wine[] = [];
  for (const w of [...BASE, ...MORE_WINES]) {
    if (seen.has(w.id)) continue;
    seen.add(w.id);
    out.push(w);
  }
  return out;
})();

export const WINE_BY_ID = new Map(WINES.map((w) => [w.id, w]));
