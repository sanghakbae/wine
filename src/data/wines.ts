export interface LabelPlace {
  /** 라벨 아래·위 높이 (cm) */
  y0: number;
  y1: number;
  /** 병을 두르는 각도 */
  arc: number;
  /** 라벨 방향 (0 = 앞) */
  turn?: number;
}

export interface Capsule {
  color: string;
  /** 0 = 무광 종이, 1 = 금속 포일 */
  metal?: number;
  rough?: number;
  /** 캡슐이 내려오는 높이 (cm, 절대값). 기본은 입구에서 5cm 아래 */
  to?: number;
}

export type Extra = "mesh" | "straw" | "flowers" | "emboss";

/** 와인 전용 문제: 질문, 정답, 오답 3개 */
export interface Trivia {
  q: string;
  a: string;
  x: [string, string, string];
}

export interface Wine {
  id: string;
  name: string;
  original: string;
  producer: string;
  /** 생산자 문제로 낼 만한가 (이름에 생산자가 그대로 들어 있으면 false) */
  producerQ?: boolean;
  country: string;
  /** 광역 산지 */
  area: string;
  /** 세부 산지 */
  sub?: string;
  grape: string;
  type: WineType;
  /** 1 = 대중적, 2 = 유명, 3 = 애호가용 */
  tier: 1 | 2 | 3;
  shape: ShapeId;
  glass: GlassKey;
  liquid: LiquidKey;
  capsule: Capsule;
  label: LabelPlace;
  neck?: LabelPlace;
  extras?: Extra[];
  fact: string;
  /** 라벨에 크게 찍을 이름 (없으면 original) */
  labelName?: string;
  /** 라벨의 생산자 표기 (원어) */
  maker?: string;
  /** 등급·퀴베 표기 (예: Premier Grand Cru Classé) */
  cls?: string;
  /** 빈티지 없는 와인 (NV) */
  nv?: boolean;
  /** 첫 빈티지 (이보다 이른 연도는 찍지 않는다) */
  since?: number;
  /** 이 와인만의 문제 */
  quiz?: Trivia[];
  /** 자동 라벨 스타일 덮어쓰기 */
  style?: Partial<LabelStyle>;
}

